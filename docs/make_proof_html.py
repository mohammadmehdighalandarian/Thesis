CELL = 32


def draw(cells, path, closed=False, cap="", hi=()):
    cells = list(cells)
    R = max(r for r, c in cells) + 1
    C = max(c for r, c in cells) + 1
    pad = 6
    width, height = C * CELL + 2 * pad, R * CELL + 2 * pad
    o = [f'<svg viewBox="0 0 {width} {height}" width="{width}" height="{height}" xmlns="http://www.w3.org/2000/svg">']
    for r, c in cells:
        fill = "var(--blk)" if (r + c) % 2 == 0 else "var(--wht)"
        o.append(f'<rect x="{pad + c * CELL}" y="{pad + r * CELL}" width="{CELL}" height="{CELL}" fill="{fill}" stroke="var(--grid)"/>')
    for r, c in hi:
        o.append(f'<rect x="{pad + c * CELL + 2}" y="{pad + r * CELL + 2}" width="{CELL - 4}" height="{CELL - 4}" fill="none" stroke="var(--warn)" stroke-width="3" rx="4"/>')
    if path:
        seq = path + [path[0]] if closed else path
        pts = " ".join(f"{pad + c * CELL + CELL / 2},{pad + r * CELL + CELL / 2}" for r, c in seq)
        o.append(f'<polyline points="{pts}" fill="none" stroke="var(--bar)" stroke-width="3.5" stroke-linejoin="round" stroke-linecap="round" opacity=".85"/>')
        for i, (r, c) in enumerate(path, 1):
            x, y = pad + c * CELL + CELL / 2, pad + r * CELL + CELL / 2
            o.append(f'<circle cx="{x}" cy="{y}" r="9" fill="var(--bg)" stroke="var(--ink2)" stroke-width=".8"/>')
            o.append(f'<text x="{x}" y="{y + 3.4}" font-size="9.5" text-anchor="middle" fill="var(--ink)" font-family="ui-monospace,monospace">{i}</text>')
        if not closed:
            for (r, c), col in ((path[0], "var(--start)"), (path[-1], "var(--end)")):
                o.append(f'<rect x="{pad + c * CELL + 1.5}" y="{pad + r * CELL + 1.5}" width="{CELL - 3}" height="{CELL - 3}" fill="none" stroke="{col}" stroke-width="3"/>')
        on = set(path)
        for r, c in cells:
            if (r, c) not in on:
                x, y = pad + c * CELL + CELL / 2, pad + r * CELL + CELL / 2
                o.append(f'<path d="M{x - 7},{y - 7}L{x + 7},{y + 7}M{x + 7},{y - 7}L{x - 7},{y + 7}" stroke="var(--miss)" stroke-width="3" stroke-linecap="round"/>')
    o.append("</svg>")
    return f'<figure>{"".join(o)}<figcaption>{cap}</figcaption></figure>'


def rect(R, C):
    return [(r, c) for r in range(R) for c in range(C)]


def m(s):
    """Inline maths, left to right."""
    return f'<span class="m">{s}</span>'


def T(p):
    return m("T(" + ", ".join(map(str, p)) + ")")


def tfig(p, cap, hi=()):
    path = longest_path(*p)
    assert len(path) == longest_length(*p)
    n = p[0] * p[1] + p[2] * p[3]
    return draw(t_cells(*p), path, cap=f"{T(p)}، {m(f'n = {n}')}، طول مسیر {m(len(path))}. {cap}", hi=hi)


